import {
  getAutoPosition,
  getElementSpecByAlias,
} from '../../../helper/diagram-helper'
import { DeploymentNode } from '../../../models/autogenerated/DeploymentNode'
import { DiagramElementSpec } from '../../../models/autogenerated/DiagramElementSpec'
import { BOX } from '../../../styles/style-constants'
import {
  C4BaseNodeBuilder,
  C4BaseNodeData,
  C4BaseNodeProps,
} from '../C4BaseNode/C4BaseNode'
import { C4Node } from '../C4DiagramCanvas/C4DiagramCanvas'
import { C4SubgraphNodeRenderingOptions } from '../C4Shapes/C4Subgraph'

export const NODE_TYPE = 'c4DeploymentNode'

export type C4DeploymentNodeProps = C4BaseNodeProps & {
  diagramElementData?: DeploymentNode
}
export type C4DeploymentNodeData = C4DeploymentNodeProps & C4BaseNodeData

type C4DeploymentNode = C4Node<C4DeploymentNodeData, 'c4DeploymentNode'>

export function C4DeploymentNodeBuilder(
  props: C4DeploymentNodeProps,
): C4DeploymentNode | undefined {
  const { diagramElementData, diagramSpec, autoLayout, renderElementsOptions } =
    props
  if (
    diagramElementData?.base_data &&
    diagramElementData.base_data.alias &&
    diagramElementData.base_data.label &&
    diagramElementData.deployment_node_type &&
    ((diagramSpec.auto_layout_enabled &&
      autoLayout[diagramElementData.base_data.alias]) ||
      !diagramSpec.auto_layout_enabled)
  ) {
    const elementSpec = getElementSpecByAlias(
      diagramElementData.base_data.alias,
      undefined,
      undefined,
      { DeploymentNode: diagramElementData.deployment_node_type },
      diagramSpec,
    )

    const renderingOptions: C4SubgraphNodeRenderingOptions = {
      bgColor:
        renderElementsOptions?.diagramsThemeSettings
          ?.bg_color_deployment_node ?? BOX.COLORS.BG_COLOR_DEPLOYMENT_NODE,
      borderColor:
        renderElementsOptions?.diagramsThemeSettings
          ?.border_color_deployment_node ??
        BOX.COLORS.BORDER_COLOR_DEPLOYMENT_NODE,
      textColor:
        renderElementsOptions?.diagramsThemeSettings
          ?.text_color_deployment_node ?? BOX.COLORS.TEXT_COLOR_DEPLOYMENT_NODE,
    }

    const defaults: DiagramElementSpec = {
      alias: diagramElementData.base_data.alias,
      position: getAutoPosition(diagramElementData.base_data.alias, autoLayout),
    }
    props.resizable = true
    props.diagramElementSpec = elementSpec
    props.renderingOptions = renderingOptions

    return {
      ...C4BaseNodeBuilder(props, defaults),
      type: NODE_TYPE,
    } as C4DeploymentNode
  }
  return
}
