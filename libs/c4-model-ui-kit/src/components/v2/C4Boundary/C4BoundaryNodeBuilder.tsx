import {
  getAutoPosition,
  getElementSpecByAlias,
} from '../../../helper/diagram-helper'
import { Boundary } from '../../../models/autogenerated/Boundary'
import { DiagramElementSpec } from '../../../models/autogenerated/DiagramElementSpec'
import { BOUNDARY, BOX } from '../../../styles/style-constants'
import {
  C4BaseNodeBuilder,
  C4BaseNodeData,
  C4BaseNodeProps,
} from '../C4BaseNode/C4BaseNode'
import { C4Node } from '../C4DiagramCanvas/C4DiagramCanvas'
import { C4SubgraphNodeRenderingOptions } from '../C4Shapes/C4Subgraph'

export const NODE_TYPE = 'c4Boundary'

export type C4BoundaryProps = C4BaseNodeProps & {
  diagramElementData?: Boundary
}
export type C4BoundaryData = C4BoundaryProps & C4BaseNodeData

type C4BoundaryNode = C4Node<C4BoundaryData, 'c4Boundary'>

export function C4BoundaryNodeBuilder(
  props: C4BoundaryProps,
): C4BoundaryNode | undefined {
  const { diagramElementData, diagramSpec, autoLayout, renderElementsOptions } =
    props
  if (
    diagramElementData?.base_data &&
    diagramElementData.base_data.alias &&
    diagramElementData.base_data.label &&
    diagramElementData.boundary_type &&
    ((diagramSpec.auto_layout_enabled &&
      autoLayout[diagramElementData.base_data.alias]) ||
      !diagramSpec.auto_layout_enabled)
  ) {
    const elementSpec = getElementSpecByAlias(
      diagramElementData.base_data.alias,
      undefined,
      undefined,
      { Boundary: diagramElementData.boundary_type },
      diagramSpec,
    )

    const renderingOptions: C4SubgraphNodeRenderingOptions = {
      bgColor:
        renderElementsOptions?.diagramsThemeSettings?.bg_color_boundary ??
        BOX.COLORS.BG_COLOR_BOUNDARY,
      borderColor:
        renderElementsOptions?.diagramsThemeSettings?.border_color_boundary ??
        BOX.COLORS.BORDER_COLOR_BOUNDARY,
      textColor:
        renderElementsOptions?.diagramsThemeSettings?.text_color_boundary ??
        BOX.COLORS.TEXT_COLOR_BOUNDARY,
      strokeDashArray: BOUNDARY.SIZES.STROKE_DASH_ARRAY,
    }

    const defaults: DiagramElementSpec = {
      alias: diagramElementData.base_data.alias,
      position: getAutoPosition(diagramElementData.base_data.alias, autoLayout),
    }
    props.resizable = true
    props.diagramElementSpec = elementSpec
    props.renderingOptions = renderingOptions

    return {
      ...C4BaseNodeBuilder(props, defaults),
      type: NODE_TYPE,
    } as C4BoundaryNode
  }
  return
}
