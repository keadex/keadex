import {
  getAutoPosition,
  getElementSpecByAlias,
} from '../../../helper/diagram-helper'
import { Component } from '../../../models/autogenerated/Component'
import { DiagramElementSpec } from '../../../models/autogenerated/DiagramElementSpec'
import { BOX } from '../../../styles/style-constants'
import {
  C4BaseNodeBuilder,
  C4BaseNodeData,
  C4BaseNodeProps,
  C4BaseNodeRenderingOptions,
} from '../C4BaseNode/C4BaseNode'
import { C4Node } from '../C4DiagramCanvas/C4DiagramCanvas'

export const COMPONENT_NODE_TYPE = 'c4Component'
export const COMPONENT_DB_NODE_TYPE = 'c4ComponentDb'
export const COMPONENT_QUEUE_NODE_TYPE = 'c4ComponentQueue'
export const COMPONENT_EXT_NODE_TYPE = 'c4ComponentExt'
export const COMPONENT_DB_EXT_NODE_TYPE = 'c4ComponentDbExt'
export const COMPONENT_QUEUE_EXT_NODE_TYPE = 'c4ComponentQueueExt'

export type C4ComponentProps = C4BaseNodeProps & {
  diagramElementData?: Component
}
export type C4ComponentData = C4ComponentProps & C4BaseNodeData

type C4ComponentNode = C4Node<C4ComponentData, 'c4Component'>
type C4ComponentDbNode = C4Node<C4ComponentData, 'c4ComponentDb'>
type C4ComponentQueueNode = C4Node<C4ComponentData, 'c4ComponentQueue'>
type C4ComponentExtNode = C4Node<C4ComponentData, 'c4ComponentExt'>
type C4ComponentDbExtNode = C4Node<C4ComponentData, 'c4ComponentDbExt'>
type C4ComponentQueueExtNode = C4Node<C4ComponentData, 'c4ComponentQueueExt'>

export function C4ComponentNodeBuilder(
  props: C4ComponentProps,
):
  | C4ComponentNode
  | C4ComponentDbNode
  | C4ComponentQueueNode
  | C4ComponentExtNode
  | C4ComponentDbExtNode
  | C4ComponentQueueExtNode
  | undefined {
  const { diagramElementData, diagramSpec, autoLayout, renderElementsOptions } =
    props
  if (
    diagramElementData?.base_data &&
    diagramElementData.base_data.alias &&
    diagramElementData.component_type &&
    ((diagramSpec.auto_layout_enabled &&
      autoLayout[diagramElementData.base_data.alias]) ||
      !diagramSpec.auto_layout_enabled)
  ) {
    const elementSpec = getElementSpecByAlias(
      diagramElementData.base_data.alias,
      undefined,
      undefined,
      { Component: diagramElementData.component_type },
      diagramSpec,
    )

    const internalRenderingOptions: C4BaseNodeRenderingOptions = {
      bgColor:
        renderElementsOptions?.diagramsThemeSettings?.bg_color_component ??
        BOX.COLORS.BG_COLOR_COMPONENT,
      borderColor:
        renderElementsOptions?.diagramsThemeSettings?.border_color_component ??
        BOX.COLORS.BORDER_COLOR_COMPONENT,
      textColor:
        renderElementsOptions?.diagramsThemeSettings?.text_color_component ??
        BOX.COLORS.TEXT_COLOR_COMPONENT,
    }

    const externalRenderingOptions: C4BaseNodeRenderingOptions = {
      bgColor:
        renderElementsOptions?.diagramsThemeSettings?.bg_color_component_ext ??
        BOX.COLORS.BG_COLOR_COMPONENT_EXT,
      borderColor:
        renderElementsOptions?.diagramsThemeSettings
          ?.border_color_component_ext ?? BOX.COLORS.BORDER_COLOR_COMPONENT_EXT,
      textColor:
        renderElementsOptions?.diagramsThemeSettings
          ?.text_color_component_ext ?? BOX.COLORS.TEXT_COLOR_COMPONENT_EXT,
    }

    let renderingOptions: C4BaseNodeRenderingOptions | undefined
    let nodeType:
      | 'c4Component'
      | 'c4ComponentDb'
      | 'c4ComponentQueue'
      | 'c4ComponentExt'
      | 'c4ComponentDbExt'
      | 'c4ComponentQueueExt' = 'c4Component'
    switch (diagramElementData.component_type) {
      case 'Component':
        nodeType = COMPONENT_NODE_TYPE
        renderingOptions = internalRenderingOptions
        break
      case 'ComponentDb':
        nodeType = COMPONENT_DB_NODE_TYPE
        renderingOptions = internalRenderingOptions
        break
      case 'ComponentQueue':
        nodeType = COMPONENT_QUEUE_NODE_TYPE
        renderingOptions = internalRenderingOptions
        break
      case 'Component_Ext':
        nodeType = COMPONENT_EXT_NODE_TYPE
        renderingOptions = externalRenderingOptions
        break
      case 'ComponentDb_Ext':
        nodeType = COMPONENT_DB_EXT_NODE_TYPE
        renderingOptions = externalRenderingOptions
        break
      case 'ComponentQueue_Ext':
        nodeType = COMPONENT_QUEUE_EXT_NODE_TYPE
        renderingOptions = externalRenderingOptions
        break
    }

    const defaults: DiagramElementSpec = {
      alias: diagramElementData.base_data.alias,
      position: getAutoPosition(diagramElementData.base_data.alias, autoLayout),
    }
    props.resizable = true
    props.diagramElementSpec = elementSpec
    props.renderingOptions = renderingOptions

    return {
      ...C4BaseNodeBuilder(props, defaults),
      type: nodeType,
    }
  }
  return
}
