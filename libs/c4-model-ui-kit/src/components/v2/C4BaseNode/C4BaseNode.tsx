import { cloneDeep } from '@keadex/keadex-utils'
import { NodeProps, NodeResizer } from '@xyflow/react'
import { ComponentType, ForwardedRef } from 'react'
import { v4 as uuidV4 } from 'uuid'

import { editableNode } from '../../../helper/react-flow-helper'
import { DiagramElementSpec } from '../../../models/autogenerated/DiagramElementSpec'
import { RenderElementsOptions } from '../../../rendering-system/v2/diagram-renderer'
import {
  C4DiagramCanvasCommands,
  C4Node,
} from '../C4DiagramCanvas/C4DiagramCanvas'

export type C4BaseNodeProps = {
  diagramElementSpec: DiagramElementSpec
  renderElementsOptions?: RenderElementsOptions
  resizable?: boolean
}

export type C4BaseNodeCoreData = {
  node?: C4Node<C4BaseNodeData>
  scaleX?: number
  scaleY?: number
  angle?: number
  getUpdatedSpecs(
    c4DiagramCanvasInstance: ForwardedRef<C4DiagramCanvasCommands>,
  ): DiagramElementSpec | undefined
}

export type C4BaseNodeData = C4BaseNodeProps & C4BaseNodeCoreData

export function C4BaseNodePropsSSRBuilder<
  T extends Record<string, unknown> & C4BaseNodeData,
  K extends string,
>(node: C4Node<T, K>): NodeProps<C4Node<T, K>> {
  const props: NodeProps<C4Node<T>> = {
    id: node.id,
    data: node.data,
    type: node.type as K,
    positionAbsoluteX: node.position.x,
    positionAbsoluteY: node.position.y,
    width: node.width,
    height: node.height,
    deletable: false,
    draggable: false,
    dragging: false,
    isConnectable: false,
    selectable: false,
    selected: false,
    zIndex: 1,
  }
  return props as NodeProps<C4Node<T, K>>
}

export function C4BaseNodeBuilder(
  props: C4BaseNodeProps,
  defaults?: DiagramElementSpec,
): Pick<C4Node<C4BaseNodeData>, 'id' | 'data' | 'position'> & Partial<C4Node> {
  // I need to calculate the scaled width and height based on the diagramElementSpec size and scale values. This because ReactFlow does not support scaleX and scaleY for nodes, so I need to calculate the scaled width and height and pass them to the node. The scaleX and scaleY are custom properties added as a convenience since they could be helpful for other purposes, but they are not used by ReactFlow.
  let scaledWidth, scaledHeight
  if (props.diagramElementSpec.size?.width) {
    scaledWidth =
      props.diagramElementSpec.size.width *
      (props.diagramElementSpec.size.scale_x ?? 1)
  }
  if (props.diagramElementSpec.size?.height) {
    scaledHeight =
      props.diagramElementSpec.size.height *
      (props.diagramElementSpec.size.scale_y ?? 1)
  }

  const newNode: C4Node<C4BaseNodeData, undefined> = {
    id: defaults?.alias ?? `c4BaseNode-${uuidV4()}`,
    data: {
      ...props,
      scaleX: props.diagramElementSpec?.size?.scale_x ?? 1,
      scaleY: props.diagramElementSpec?.size?.scale_y ?? 1,
      angle: props.diagramElementSpec?.position?.angle ?? 0,

      getUpdatedSpecs(
        c4DiagramCanvasRef: ForwardedRef<C4DiagramCanvasCommands>,
      ): DiagramElementSpec | undefined {
        let c4DiagramCanvasInstance:
          | C4DiagramCanvasCommands
          | null
          | undefined = null
        if (typeof c4DiagramCanvasRef === 'function') {
          throw new Error('C4DiagramCanvas not initialized yet')
        } else {
          c4DiagramCanvasInstance = c4DiagramCanvasRef?.current
        }

        const oldDiagramElementSpec = this.diagramElementSpec
        if (oldDiagramElementSpec) {
          const newDiagramElementSpec = cloneDeep(oldDiagramElementSpec)
          newDiagramElementSpec.position = {
            left: this.node?.position.x ?? oldDiagramElementSpec.position?.left,
            top: this.node?.position.y ?? oldDiagramElementSpec.position?.top,
            z_index:
              this.node?.zIndex ?? oldDiagramElementSpec.position?.z_index,
            angle: this.angle ?? oldDiagramElementSpec.position?.angle,
          }
          newDiagramElementSpec.size = {
            width: this.node?.width ?? oldDiagramElementSpec.size?.width,
            height: this.node?.height ?? oldDiagramElementSpec.size?.height,
            scale_x: this.scaleX ?? oldDiagramElementSpec.size?.scale_x,
            scale_y: this.scaleY ?? oldDiagramElementSpec.size?.scale_y,
          }
          return newDiagramElementSpec
        } else {
          // TODO - create if not defined spec
        }
        return
      },
    },
    position: {
      x:
        props.diagramElementSpec?.position?.left ??
        defaults?.position?.left ??
        0,
      y:
        props.diagramElementSpec?.position?.top ?? defaults?.position?.top ?? 0,
    },
    width: scaledWidth,
    height: scaledHeight,
    zIndex: props.diagramElementSpec?.position?.z_index ?? 1,
    ...editableNode(props.resizable),
  }
  newNode.data.node = newNode
  return newNode
}

export function withC4BaseNode<
  T extends Record<string, unknown> & C4BaseNodeData,
  K extends string,
>(
  Component: ComponentType<NodeProps<C4Node<T, K>>>,
): ComponentType<NodeProps<C4Node<T, K>>> {
  return function C4BaseNode(node: NodeProps<C4Node<T, K>>) {
    const resizable =
      node.data.resizable === undefined || node.data.resizable === true
    return (
      <>
        {resizable && (
          <NodeResizer
            color="#ff0071"
            isVisible={node.selected}
            keepAspectRatio={true}
          />
        )}
        <Component {...node} />
      </>
    )
  }
}
