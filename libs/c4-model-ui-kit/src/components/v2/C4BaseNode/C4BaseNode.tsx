export type C4BaseNodeCoreData = {
  scaleX?: number
  scaleY?: number
  angle?: number
  getUpdatedSpecs(
    node: C4Node<C4BaseNodeData, undefined>,
  ): DiagramElementSpec | undefined
}

export type C4BaseNodeData = C4BaseNodeProps & C4BaseNodeCoreData

export function C4BaseNodePropsSSRBuilder<
  T extends Record<string, unknown> & C4BaseNodeData,
  K extends string,
>(node: C4Node<T, K>): NodeProps<C4Node<T, K>> {
  const props: NodeProps<C4Node<T>> = {
    id: node.id,
    data: node.data,
    type: node.type as K,
    positionAbsoluteX: node.position.x,
    positionAbsoluteY: node.position.y,
    width: node.width,
    height: node.height,
    deletable: false,
    draggable: false,
    dragging: false,
    isConnectable: false,
    selectable: false,
    selected: false,
    zIndex: 1,
  }
  return props as NodeProps<C4Node<T, K>>
}

export function C4BaseNodeBuilder(
  props: C4BaseNodeProps,
  defaults?: DiagramElementSpec,
): Pick<C4Node<C4BaseNodeData>, 'id' | 'data' | 'position'> & Partial<C4Node> {
  const { diagramElementData, autoLayout, parentNode, tempNodesMap } = props
  let { diagramElementSpec } = props

  // If this is a subgraph node, then the diagramElementSpec of the "parent" box is the rectangle shape spec.
  // Subgraph parent box size could be defined by the autolayout rendering system.
  let autoSize
  let rootDiagramElementSpec
  if (
    diagramElementSpec &&
    diagramElementData?.sub_elements &&
    diagramElementData.sub_elements.length > 0
  ) {
    const parentBoxSpec = diagramElementSpec?.shapes?.find(
      (shape) => shape.shape_type === SubgraphObjects.Rectangle,
    )
    rootDiagramElementSpec = diagramElementSpec
    diagramElementSpec = parentBoxSpec
    autoSize = getAutoSize(rootDiagramElementSpec.alias, autoLayout)
  }

  // I need to calculate the scaled width and height based on the diagramElementSpec size and scale values. This because ReactFlow does not support scaleX and scaleY for nodes, so I need to calculate the scaled width and height and pass them to the node. The scaleX and scaleY are custom properties added as a convenience since they could be helpful for other purposes, but they are not used by ReactFlow.
  let scaledWidth, scaledHeight
  if (diagramElementSpec?.size?.width) {
    scaledWidth =
      autoSize?.width ??
      diagramElementSpec.size.width * (diagramElementSpec.size.scale_x ?? 1)
  }
  if (diagramElementSpec?.size?.height) {
    scaledHeight =
      autoSize?.height ??
      diagramElementSpec.size.height * (diagramElementSpec.size.scale_y ?? 1)
  }

  const editable =
    (props.resizable === undefined || props.resizable === true) &&
    !props.renderElementsOptions?.readOnly

  const parentNodeAbsolutePosition = getAbsolutePosition(
    parentNode,
    tempNodesMap,
  )
  const newNodePosition = toRelativePosition(
    {
      x: diagramElementSpec?.position?.left ?? defaults?.position?.left ?? 0,
      y: diagramElementSpec?.position?.top ?? defaults?.position?.top ?? 0,
    },
    parentNodeAbsolutePosition,
  )

  let newNode: C4Node<C4BaseNodeData, undefined> = {
    id: defaults?.alias ?? `c4BaseNode-${uuidV4()}`,
    data: {
      ...props,
      scaleX: diagramElementSpec?.size?.scale_x ?? 1,
      scaleY: diagramElementSpec?.size?.scale_y ?? 1,
      angle: diagramElementSpec?.position?.angle ?? 0,

      getUpdatedSpecs(
        node: C4Node<C4BaseNodeData, undefined>,
      ): DiagramElementSpec | undefined {
        const oldDiagramElementSpec = this.diagramElementSpec
        if (oldDiagramElementSpec) {
          const newDiagramElementSpec = cloneDeep(oldDiagramElementSpec)
          newDiagramElementSpec.position = {
            left: node.position.x ?? oldDiagramElementSpec.position?.left,
            top: node.position.y ?? oldDiagramElementSpec.position?.top,
            z_index: node.zIndex ?? oldDiagramElementSpec.position?.z_index,
            angle: this.angle ?? oldDiagramElementSpec.position?.angle,
          }

          // width and height must be saved unscaled, since they are scaled on the fly by the rendering system based on the scaleX and scaleY values.
          newDiagramElementSpec.size = {
            width: node.width
              ? node.width /
                (this.scaleX ?? oldDiagramElementSpec.size?.scale_x ?? 1)
              : oldDiagramElementSpec.size?.width,
            height: node.height
              ? node.height /
                (this.scaleY ?? oldDiagramElementSpec.size?.scale_y ?? 1)
              : oldDiagramElementSpec.size?.height,
            scale_x: this.scaleX ?? oldDiagramElementSpec.size?.scale_x,
            scale_y: this.scaleY ?? oldDiagramElementSpec.size?.scale_y,
          }
          return newDiagramElementSpec
        } else {
          // TODO - create if not defined spec
        }
        return
      },

      contextMenuHandler:
        props.contextMenuHandler ??
        ((c4DiagramCanvasRef, event, node, contextMenuItems?) => {
          const pointer = { x: event.clientX, y: event.clientY }
          const newEvent = new CustomEvent<KeadexContextMenuEvent>(
            GENERIC_EVENTS.CONTEXT_MENU,
            {
              detail: {
                sourceEvent: event,
                pageX: pointer.x,
                pageY: pointer.y,
                menuItems:
                  contextMenuItems ??
                  createBaseContextMenuItems(
                    canvasRefToInstance(c4DiagramCanvasRef),
                    event,
                    node,
                  ),
              },
            },
          )
          document.dispatchEvent(newEvent)
        }),
    },
    position: newNodePosition,
    width: scaledWidth,
    height: scaledHeight,
    zIndex: diagramElementSpec?.position?.z_index ?? 1,
    parentId: parentNode?.id,
  }
  newNode = editableNode(newNode, editable)
  newNode = readOnlyNode(newNode, props.renderElementsOptions?.readOnly)
  return newNode
}

export function withC4BaseNode<
  T extends Record<string, unknown> & C4BaseNodeData,
  K extends string,
>(
  Component: ComponentType<NodeProps<C4Node<T, K>>>,
): ComponentType<NodeProps<C4Node<T, K>>> {
  return function C4BaseNode(node: NodeProps<C4Node<T, K>>) {
    const naturalSizeRef = useRef<{ width: number; height: number } | null>(
      null,
    )

    const resizable =
      node.data.resizable === undefined || node.data.resizable === true
    const readOnly =
      node.data.renderElementsOptions?.readOnly === undefined
        ? false
        : node.data.renderElementsOptions?.readOnly

    const onResizeStart: OnResizeStart = (event, params) => {
      naturalSizeRef.current = {
        width: (node.width ?? 1) / (node.data.scaleX ?? 1),
        height: (node.height ?? 1) / (node.data.scaleY ?? 1),
      }
    }

    const onResizeEnd: OnResizeEnd = (event, params) => {
      naturalSizeRef.current = null
    }

    const onResize: OnResize = (event, params) => {
      if (!naturalSizeRef.current) return // safety guard

      // Compute the new scale from the anchor
      const newScaleX = params.width / naturalSizeRef.current.width
      const newScaleY = params.height / naturalSizeRef.current.height

      node.data.scaleX = newScaleX
      node.data.scaleY = newScaleY
    }

    const handleContextMenu = useCallback(
      (event: React.MouseEvent<HTMLDivElement, MouseEvent>) => {
        if (node.data.contextMenuHandler) {
          console.debug('C4BaseNode handleContextMenu', { node, event })
          node.data.contextMenuHandler?.(
            node.data.c4DiagramCanvasRef,
            event,
            node as unknown as C4Node<C4BaseNodeData, undefined>,
          )
        } else {
          console.warn(
            'C4BaseNode handleContextMenu: No contextMenuHandler defined for node',
            node,
          )
        }
      },
      [node],
    )

    return (
      <div
        onContextMenu={handleContextMenu}
        data-alias={
          node.data.diagramElementData?.base_data?.alias ?? 'undefined'
        }
      >
        {!readOnly && resizable && (
          <NodeResizer
            color="#ff0071"
            isVisible={node.selected}
            keepAspectRatio={true}
            onResize={onResize}
            onResizeStart={onResizeStart}
            onResizeEnd={onResizeEnd}
          />
        )}
        <Component {...node} />
      </div>
    )
  }
}
